    getSite(siteId, language = 'en') {
        const site = this.sites[siteId];
        if (!site) return null;

        return {
            id: site.id,
            name: site.name[language] || site.name.en,
            description: site.description[language] || site.description.en,
            features: site.features[language] || site.features.en,
            position: site.position
        };
    }

    getArtifact(artifactId, language = 'en') {
        const artifact = this.artifacts[artifactId];
        if (!artifact) return null;

        return {
            name: artifact.name[language] || artifact.name.en,
            description: artifact.description[language] || artifact.description.en
        };
    }

    getAllSites(language = 'en') {
        return Object.keys(this.sites).map(siteId => this.getSite(siteId, language));
    }

    getTimeline(period, language = 'en') {
        const timelineEntry = this.timeline[period];
        if (!timelineEntry) return null;

        return {
            period: timelineEntry.period[language] || timelineEntry.period.en,
            events: timelineEntry.events[language] || timelineEntry.events.en
        };
    }
