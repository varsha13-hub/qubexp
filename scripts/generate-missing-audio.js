async function generateAudio(text, lang, key) {
  try {
    process.env.NODE_TLS_REJECT_UNAUTHORIZED = '0';  // Allow self-signed certificates
    const response = await fetch('https://localhost:8040/api/tts', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        text,
        language: lang,
        response_type: 'audio_base64'
      })
    });

    if (!response.ok) {
      throw new Error(`HTTP error! status: ${response.status}`);
    }

    const data = await response.json();
    if (!data.audio) {
      throw new Error('No audio data received');
    }

    // Save the audio file
    const audioDir = path.join(__dirname, '..', 'solar-system', 'audio', lang);
    await fs.mkdir(audioDir, { recursive: true });
    
    const audioPath = path.join(audioDir, `${key}.mp3`);
    await fs.writeFile(audioPath, Buffer.from(data.audio, 'base64'));
    
    console.log(`✅ Generated: ${lang}/${key}.mp3`);
  } catch (error) {
    console.error(`❌ Error generating ${lang}/${key}.mp3:`, error);
  }
}

async function generateAllMissingAudio() {
  console.log('🎵 Starting audio generation for missing files...\n');

  for (const lang of MISSING_LANGS) {
    console.log(`\n📂 Language: ${lang}`);
    for (const key of KEYS) {
      if (CONTENT[key] && CONTENT[key][lang]) {
        await generateAudio(CONTENT[key][lang], lang, key);
      } else {
        console.log(`⚠️  Missing content for ${lang}/${key}`);
      }
    }
  }
}

